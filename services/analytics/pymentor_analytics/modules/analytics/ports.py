"""Public unit-of-work boundary; one instance per request or task."""
from typing import AsyncContextManager, Protocol
from uuid import UUID
from pymentor_analytics.contracts.processing_v1 import ClaimedBatch, SyntheticCountSnapshot, SyntheticDelta
from pymentor_analytics.contracts.replay_v1 import ReplayHandle, ReplayState


class UnitOfWorkFactory(Protocol):
    def transaction(self) -> AsyncContextManager: ...


class ProcessorStore(Protocol):
    async def claim(self, consumer: str, version: int, worker: UUID, limit: int, lease_seconds: int) -> ClaimedBatch | None: ...
    async def renew(self, batch: ClaimedBatch, lease_seconds: int) -> bool: ...
    async def commit(self, batch: ClaimedBatch, effect: SyntheticDelta) -> None: ...
    async def fail(self, batch: ClaimedBatch) -> str: ...
    async def release(self, batch: ClaimedBatch) -> bool: ...


class SyntheticCountsReader(Protocol):
    """Caller must authorize subject and every requested course before reading."""
    async def read_counts(self, consumer: str, version: int, actor: UUID, subject: UUID,
                          course_ids: tuple[str, ...]) -> SyntheticCountSnapshot | None: ...


class ReplayStore(Protocol):
    async def begin(self, consumer: str, version: int, subject: UUID, request_id: UUID) -> ReplayState: ...
    async def step(self, handle: ReplayHandle, limit: int = 100) -> ReplayState: ...
    async def finish(self, handle: ReplayHandle) -> ReplayState: ...
