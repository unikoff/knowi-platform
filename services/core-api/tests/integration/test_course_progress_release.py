def _migrate(url, action, revision):
    env = {key: value for key, value in os.environ.items()
           if key in {"PATH", "SYSTEMROOT", "WINDIR", "TEMP", "TMP"}}
    env.update({
        "KNOWI_MIGRATION_URL": url.set(drivername="postgresql+asyncpg").render_as_string(hide_password=False),
        "KNOWI_MIGRATION_HOST": "127.0.0.1",
        "KNOWI_MIGRATION_DATABASE": url.database,
        "KNOWI_MIGRATION_USER": url.username,
    })
    script = (
        "from alembic import command; from alembic.config import Config; "
        "import sys; c=Config(sys.argv[1]); c.set_main_option('core_runtime_migrations','true'); "
        "getattr(command,sys.argv[2])(c,sys.argv[3])"
    )
    return subprocess.run([sys.executable, "-c", script, str(CORE / "alembic.ini"), action, revision],
                          env=env, capture_output=True, text=True, timeout=90)


def _snapshot(connection):
    with connection.cursor() as cur:
        cur.execute("SELECT version_num FROM alembic_version")
        revision = cur.fetchone()[0]
        cur.execute("SELECT id,user_id,lesson_id,completed_at FROM user_lesson_progress ORDER BY id")
        lessons = cur.fetchall()
        cur.execute("SELECT id,user_id,task_id,task_revision,completed_at FROM user_task_progress ORDER BY id")
        tasks = cur.fetchall()
        cur.execute("SELECT table_name,column_name FROM information_schema.columns WHERE table_schema='public' AND table_name IN ('user_lesson_progress','user_task_progress') ORDER BY 1,2")
        columns = cur.fetchall()
        cur.execute("SELECT conrelid::regclass::text,conname,pg_get_constraintdef(oid) FROM pg_constraint WHERE conrelid IN ('user_lesson_progress'::regclass,'user_task_progress'::regclass) ORDER BY 1,2")
        constraints = cur.fetchall()
    connection.commit()
    return revision, lessons, tasks, columns, constraints


def test_release_migration_transaction_and_course_isolation(disposable_database):
    url = disposable_database
    dsn = url.render_as_string(hide_password=False)
    result = _migrate(url, "upgrade", OLD)
    assert result.returncode == 0, result.stderr
    with psycopg.connect(dsn) as conn:
        with conn.cursor() as cur:
            cur.execute("INSERT INTO users (id,username,email,password_hash) VALUES (91,'Synthetic','c504@example.test','synthetic')")
            cur.execute("INSERT INTO user_lesson_progress (id,user_id,lesson_id,completed_at) VALUES (101,91,'historical-урок','2020-01-02 03:04:05+00')")
            cur.execute("INSERT INTO user_task_progress (id,user_id,task_id,task_revision,completed_at) VALUES (201,91,'historical-задача','revision-α','2021-02-03 04:05:06+00')")
        conn.commit()
        before = _snapshot(conn)
        assert before[0] == OLD
        # A concurrent reader blocks the second table's ACCESS EXCLUSIVE DDL.
        with psycopg.connect(dsn) as blocker:
            blocker.execute("LOCK TABLE user_task_progress IN ACCESS SHARE MODE")
            failed = _migrate(url, "upgrade", NEW)
            assert failed.returncode != 0 and "lock timeout" in failed.stderr.lower(), failed.stderr
            blocker.rollback()
        assert _snapshot(conn) == before  # first-table DDL and Alembic head rolled back
        result = _migrate(url, "upgrade", NEW)
        assert result.returncode == 0, result.stderr
        after = _snapshot(conn)
        assert after[0] == NEW and after[1:3] == before[1:3]
        with conn.cursor() as cur:
            for table in ("user_lesson_progress", "user_task_progress"):
                cur.execute(sql.SQL("SELECT course_id FROM {} ").format(sql.Identifier(table)))
                assert cur.fetchall() == [("backend",)]
            cur.execute("INSERT INTO user_lesson_progress (id,user_id,lesson_id,course_id) VALUES (102,91,'historical-урок','backend_copy')")
            cur.execute("INSERT INTO user_task_progress (id,user_id,task_id,task_revision,course_id) VALUES (202,91,'historical-задача','copy-revision','backend_copy')")
        conn.commit()
        for table, entity in (("user_lesson_progress", "lesson"), ("user_task_progress", "task")):
            with pytest.raises(psycopg.errors.UniqueViolation):
                with conn.cursor() as cur:
                    if entity == "lesson":
                        cur.execute("INSERT INTO user_lesson_progress (id,user_id,lesson_id,course_id) VALUES (103,91,'historical-урок','backend')")
                    else:
                        cur.execute("INSERT INTO user_task_progress (id,user_id,task_id,task_revision,course_id) VALUES (203,91,'historical-задача','x','backend')")
            conn.rollback()
        stable = _snapshot(conn)
        # Rehearse c504 specifically even after later release heads are introduced.
        assert _migrate(url, "upgrade", NEW).returncode == 0
        assert _snapshot(conn) == stable
        refused = _migrate(url, "downgrade", OLD)
        assert refused.returncode != 0 and "Refusing to merge or discard" in refused.stderr
        assert _snapshot(conn) == stable


@pytest.fixture
def disposable_member_database():
    raw = os.environ.get("KNOWI_TEST_PG_URL")
    if not raw:
        pytest.skip("KNOWI_TEST_PG_URL is required for disposable PostgreSQL 16 rehearsal")
    base = _allowlisted_url(raw)
    suffix = uuid4().hex
    db, owner, member = (prefix + suffix for prefix in
                         ("c504_release_ci_", "c504_owner_", "c504_member_"))
    patterns = (r"c504_release_ci_[0-9a-f]{32}", r"c504_owner_[0-9a-f]{32}",
                r"c504_member_[0-9a-f]{32}")
    assert all(re.fullmatch(pattern, name) for pattern, name in zip(patterns, (db, owner, member)))
    password = secrets.token_urlsafe(32)
    created = []
    admin_dsn = base.set(drivername="postgresql").render_as_string(hide_password=False)
    with psycopg.connect(admin_dsn, autocommit=True) as admin:
        try:
            with admin.cursor() as cur:
                cur.execute("SELECT current_database(), current_user, current_setting('server_version_num')::int")
                database, user, version = cur.fetchone()
                if (database, user) != ("pymentor_test", "pymentor_test") or not 160000 <= version < 170000:
                    raise RuntimeError("Connected server is not the allowlisted PostgreSQL 16 test instance")
                for role in (owner, member):
                    cur.execute(sql.SQL("CREATE ROLE {} LOGIN INHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS PASSWORD {}")
                                .format(sql.Identifier(role), sql.Literal(password)))
                    created.append(role)
                cur.execute(sql.SQL("GRANT {} TO {}").format(sql.Identifier(owner), sql.Identifier(member)))
                cur.execute(sql.SQL("CREATE DATABASE {} OWNER {}").format(sql.Identifier(db), sql.Identifier(owner)))
                created.append(db)
            yield (base.set(drivername="postgresql", database=db, username=owner, password=password),
                   base.set(drivername="postgresql", database=db, username=member, password=password),
                   owner, member)
        finally:
            # Drop the database first; only successfully created, locally generated names qualify.
            assert all(re.fullmatch(pattern, name) for pattern, name in zip(patterns, (db, owner, member)))
            with admin.cursor() as cur:
                if db in created:
                    cur.execute(sql.SQL("DROP DATABASE {}").format(sql.Identifier(db)))
                for role in (member, owner):
                    if role in created:
                        cur.execute(sql.SQL("DROP ROLE {}").format(sql.Identifier(role)))


def test_c504_migration_by_inherited_owner_member(disposable_member_database):
    owner_url, member_url, owner, member = disposable_member_database
    result = _migrate(owner_url, "upgrade", OLD)
    assert result.returncode == 0, result.stderr
    with psycopg.connect(owner_url.render_as_string(hide_password=False)) as conn:
        with conn.cursor() as cur:
            cur.execute("INSERT INTO users (id,username,email,password_hash) VALUES (91,'Synthetic','c504@example.test','synthetic')")
            cur.execute("INSERT INTO user_lesson_progress (id,user_id,lesson_id,completed_at) VALUES (101,91,'historical','2020-01-02 03:04:05+00')")
            cur.execute("INSERT INTO user_task_progress (id,user_id,task_id,task_revision,completed_at) VALUES (201,91,'historical','revision','2021-02-03 04:05:06+00')")
            cur.execute(sql.SQL("GRANT SELECT ON user_lesson_progress, user_task_progress TO {}").format(sql.Identifier(member)))
        conn.commit()
        before = _snapshot(conn)
        with conn.cursor() as cur:
            cur.execute("SELECT relname, pg_get_userbyid(relowner), relacl::text FROM pg_class WHERE oid IN ('user_lesson_progress'::regclass, 'user_task_progress'::regclass) ORDER BY relname")
            ownership_and_grants = cur.fetchall()
        conn.commit()
        result = _migrate(member_url, "upgrade", NEW)
        assert result.returncode == 0, result.stderr
        after = _snapshot(conn)
        assert before[0] == OLD and after[0] == NEW and after[1:3] == before[1:3]
        with conn.cursor() as cur:
            cur.execute("SELECT relname, pg_get_userbyid(relowner), relacl::text FROM pg_class WHERE oid IN ('user_lesson_progress'::regclass, 'user_task_progress'::regclass) ORDER BY relname")
            assert cur.fetchall() == ownership_and_grants
            assert all(row[1] == owner for row in ownership_and_grants)
            cur.execute("SELECT count(*) FROM pg_shdepend WHERE refclassid = 'pg_authid'::regclass AND refobjid = (SELECT oid FROM pg_roles WHERE rolname = %s) AND deptype = 'o'", (member,))
            assert cur.fetchone()[0] == 0
            for table in ("user_lesson_progress", "user_task_progress"):
                cur.execute(sql.SQL("SELECT course_id FROM {}").format(sql.Identifier(table)))
                assert cur.fetchall() == [("backend",)]
