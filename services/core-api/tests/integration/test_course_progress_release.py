CORE = Path(__file__).resolve().parents[2]
OLD = "c503_dual_email_change"
NEW = "c504_course_progress"
PREFIX = "c504_release_ci_"


def _allowlisted_url(raw: str):
    try:
        url = make_url(raw)
        valid = (
            url.drivername in {"postgresql", "postgresql+asyncpg", "postgresql+psycopg"}
            and (url.host, url.port, url.database, url.username)
            == ("127.0.0.1", 57382, "pymentor_test", "pymentor_test")
            and not url.query
        )
    except Exception:
        valid = False
    if not valid:
        raise ValueError("PostgreSQL URL outside disposable allowlist") from None
    return url


def test_url_guard_rejects_other_targets():
    valid = "postgresql://pymentor_test:synthetic@127.0.0.1:57382/pymentor_test"
    assert _allowlisted_url(valid).database == "pymentor_test"
    for raw in (valid.replace("57382", "5432"), valid.replace("127.0.0.1", "localhost"),
                valid.replace("/pymentor_test", "/production"),
                valid.replace("pymentor_test:synthetic", "other:synthetic"), valid + "?host=elsewhere"):
        with pytest.raises(ValueError):
            _allowlisted_url(raw)


