from pathlib import Path
import sqlite3

def backup_database(source: Path, destination: Path) -> Path:
    source = source.resolve(strict=True)
    destination = destination.resolve()
    if not source.is_file():
        raise ValueError("Источник должен быть файлом")
    if source == destination:
        raise ValueError("Источник и назначение совпали")
    if not destination.parent.is_dir():
        raise ValueError("Каталог назначения не существует")
    with closing(sqlite3.connect(source.as_uri() + "?mode=ro", uri=True)) as reader:
        reader.execute("SELECT name FROM sqlite_schema").fetchall()
        with destination.open("xb"):
            pass
        with closing(sqlite3.connect(destination)) as writer:
            reader.backup(writer)
    with closing(sqlite3.connect(destination.as_uri() + "?mode=ro", uri=True)) as check:
        check.execute("SELECT name FROM sqlite_schema").fetchall()
    return destination

if __name__ == "__main__":
    source = Path("data/backup-work/planner-source.sqlite3")
    destination = Path("data/backup-work/planner-reserve.sqlite3")
    print(backup_database(source, destination))
